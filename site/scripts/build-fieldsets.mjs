// Which fields a cartridge of each family actually has, computed from the dataset.
//
// Generate family-specific field sets so the form prioritises fields present in that family.
// Recompute them at build time to keep them aligned with the current dataset.
//
// The threshold is stated rather than tuned: a field is in a family's working set when **at least
// 90 % of that family's records carry it**. Changing this threshold changes the form.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CARTRIDGES } from './records.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, '..', 'src', 'lib', 'fieldsets.generated.json');

/** The families a cartridge designer can serve: those whose groups are flat records of figures. */
const METALLIC = ['belted', 'pistol', 'rimfire', 'rimless', 'rimmed'];

/** Present on this share of a family's records, or it is not part of that family's form. */
const WORKING_SET_SHARE = 0.9;

/** Flatten one record to the set of field paths it actually populates. */
function fieldsOf(record) {
  const found = new Set();
  for (const side of ['cartridge', 'chamber']) {
    const groups = record[side];
    if (!groups) continue;
    for (const [group, body] of Object.entries(groups)) {
      // A repeating group - a shot cartridge's rows - is not a set of fields and is not offered
      // by this form. Recorded as the group itself so nothing is silently dropped.
      if (Array.isArray(body)) {
        found.add(`${side}.${group}[]`);
        continue;
      }
      for (const [field, value] of Object.entries(body)) {
        // `null` is the dataset's way of saying the sheet does not print it. That is an absence,
        // not a value, and counting it would put fields in a working set that nobody ever fills.
        if (value === null || value === undefined) continue;
        const path = `${side}.${group}.${field}`;
        if (typeof value === 'object' && 'degrees' in value) angleFields.add(path);
        found.add(path);
      }
    }
  }
  return found;
}

const perFamily = {};
const everyRecordFields = [];
// Which paths hold an angle rather than a number. The sheets print these as degrees, minutes and
// seconds, and a form cannot know that from an empty field - so it is recorded here, where the
// records can say it, rather than guessed from the field's name.
const angleFields = new Set();

for (const family of METALLIC) {
  let files;
  try {
    files = readdirSync(join(CARTRIDGES, family)).filter((f) => f.endsWith('.json'));
  } catch {
    continue;
  }
  const counts = new Map();
  let records = 0;
  for (const file of files) {
    const record = JSON.parse(readFileSync(join(CARTRIDGES, family, file), 'utf8'));
    const fields = fieldsOf(record);
    everyRecordFields.push(fields);
    records += 1;
    for (const field of fields) counts.set(field, (counts.get(field) ?? 0) + 1);
  }
  if (records === 0) continue;

  const all = [...counts.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  perFamily[family] = {
    records,
    working: all.filter(([, n]) => n / records >= WORKING_SET_SHARE).map(([field]) => field),
    rare: all.filter(([, n]) => n / records < WORKING_SET_SHARE).map(([field]) => field),
    counts: Object.fromEntries(all)
  };
}

// The shared core: in every family's working set. This is what a form shows before the family is
// even chosen, and what makes "start from a neighbour" possible across families.
const families = Object.keys(perFamily);
const shared = families.length
  ? perFamily[families[0]].working.filter((field) =>
      families.every((family) => perFamily[family].working.includes(field))
    )
  : [];

const distinct = new Set();
for (const fields of everyRecordFields) for (const field of fields) distinct.add(field);

const out = {
  note: 'Generated by scripts/build-fieldsets.mjs. Do not edit.',
  workingSetShare: WORKING_SET_SHARE,
  records: everyRecordFields.length,
  distinctFields: distinct.size,
  shared,
  angleFields: [...angleFields].sort(),
  families: perFamily
};

writeFileSync(OUT, `${JSON.stringify(out, null, 1)}\n`);

const summary = families
  .map((f) => `${f} ${perFamily[f].working.length}/${perFamily[f].records}`)
  .join(', ');
console.log(
  `fieldsets: ${out.records} records, ${out.distinctFields} distinct fields, ` +
    `${shared.length} shared, ${angleFields.size} angles; working sets ${summary}`
);
